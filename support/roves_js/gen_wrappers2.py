"""Generates roves-js's `rust::wrappers2` list from mozjs's.

Usage: gen_wrappers2.py [--check] <mozjs src dir> <roves-js src dir> <out.rs>

mozjs builds `rust::wrappers2` (the `&mut JSContext` / Rust-handle wrappers) by running its
`wrap!` macro over `jsapi2_wrappers.in.rs` and `glue2_wrappers.in.rs`. roves-js reuses the
same macro and keeps the entries whose function it implements: the name must be reachable
as `crate::jsapi::NAME` (for `jsapi` entries) or `crate::glue::NAME` (for `glue` entries),
and must not already be written by hand in `rust.rs`'s `wrappers2` module. `ROVES_ENTRIES`
adds the wrappers of roves-js functions mozjs's lists lack. `--check` only compares.
"""

import os
import re
import sys

FN = re.compile(r"^\s*pub (?:unsafe )?(?:extern \"C\" )?fn (\w+)", re.M)


def read(path):
    with open(path, encoding="utf-8") as file:
        return file.read()


# Functions generated by roves-js's own macros (`typed_array!` arguments and
# `typed_array_with_buffer!` arms).
MACRO_FN = re.compile(r"\b((?:JS_|Get|Unwrap)\w+)\b")


def defined(path):
    text = read(path)
    names = set(FN.findall(text))
    for invocation in re.findall(r"typed_array!\((.*?)\);", text, re.S):
        names.update(MACRO_FN.findall(invocation))
    names.update(re.findall(r"^\s*(JS_\w+) =>", text, re.M))
    return names


def reexports(text, module):
    """Names re-exported with `pub use crate::<module>::{...}` / `::*` / `::Name`."""
    names = set()
    glob = False
    for match in re.finditer(r"pub use crate::(\w+)::(\{[^}]*\}|\*|\w+);", text):
        if match.group(1) != module:
            continue
        items = match.group(2)
        if items == "*":
            glob = True
        else:
            names.update(re.findall(r"\w+", items))
    return names, glob


def visible(src, module_file):
    """The function names a module (`jsapi.rs` / `glue.rs`) makes reachable."""
    text = read(os.path.join(src, module_file))
    names = defined(os.path.join(src, module_file))
    for module in ("jsapi_impl", "binding", "realm_impl", "api", "object", "native", "proxy", "typedarray_impl", "runtime_impl", "script_impl", "values_impl", "modules_impl", "structured_clone_impl"):
        explicit, glob = reexports(text, module)
        path = os.path.join(src, module + ".rs")
        if glob:
            names |= defined(path)
        names |= explicit & defined(path)
    return names


def handwritten(src):
    text = read(os.path.join(src, "rust.rs"))
    start = text.index("pub mod wrappers2 {")
    return set(FN.findall(text[start:]))


ENTRY = re.compile(r"wrap!\((\w+): pub fn (\w+)\(")

# Wrappers of roves-js functions that mozjs 0.21's lists do not have, each written after the
# mozjs entry it follows (same mutability and handle conventions as mozjs's entries).
ROVES_ENTRIES = {
    "JS_NewEnumerateStandardClasses": [
        "wrap!(jsapi: pub fn JS_InitGlobalInterfaceProperties(cx: &mut JSContext, obj: HandleObject) -> bool);",
    ],
    "JobQueueMayNotBeEmpty": [
        "wrap!(jsapi: pub fn PerformMicrotaskCheckpoint(cx: &mut JSContext));",
    ],
    "NewWindowProxy": [
        "wrap!(glue: pub fn GetCrossOriginPropertyHolder(cx: &mut JSContext, proxy: HandleObject, holder: MutableHandleObject) -> bool);",
        "wrap!(glue: pub fn SetCrossOriginPropertyHolder(cx: &mut JSContext, proxy: HandleObject, holder: HandleObject) -> bool);",
    ],
}


def generate(mozjs, src):
    """The generated file's text and the number of skipped mozjs entries. Reads only."""
    available = {"jsapi": visible(src, "jsapi.rs"), "glue": visible(src, "glue.rs")}
    manual = handwritten(src)
    kept = []
    skipped = 0
    anchors = set()
    for name in ("jsapi2_wrappers.in.rs", "glue2_wrappers.in.rs"):
        for line in read(os.path.join(mozjs, name)).splitlines():
            entry = ENTRY.match(line)
            if not entry:
                continue
            module, function = entry.groups()
            if function in available[module] and function not in manual:
                kept.append(line)
                if function in ROVES_ENTRIES:
                    anchors.add(function)
                    kept.extend(ROVES_ENTRIES[function])
            else:
                skipped += 1
    for anchor, lines in ROVES_ENTRIES.items():
        if anchor not in anchors:
            raise SystemExit(f"anchor {anchor} of a roves-js entry was not generated")
        for line in lines:
            module, function = ENTRY.match(line).groups()
            if function not in available[module] or function in manual:
                raise SystemExit(f"roves-js entry {function} is not crate::{module}::{function}")
    header = ("// Generated by support/roves_js/gen_wrappers2.py from mozjs's wrapper lists:\n"
              "// the entries roves-js implements. Do not edit by hand.\n")
    return header + "".join(line + "\n" for line in kept), skipped


def main():
    args = sys.argv[1:]
    check = args[:1] == ["--check"]
    mozjs, src, out = args[check:]
    text, skipped = generate(mozjs, src)
    if check:
        with open(out, encoding="utf-8", newline="") as current:
            if current.read() != text:
                sys.exit(f"{out} differs from the generator's output")
        print(f"{out} is up to date")
        return
    with open(out, "w", encoding="utf-8", newline="\n") as output:
        output.write(text)
    print(f"kept {text.count(chr(10)) - 2} wrappers, skipped {skipped}")


if __name__ == "__main__":
    main()
