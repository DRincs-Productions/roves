//! Rasterizes the startup-screen "Roves" wordmark with the official font (repository
//! `resources/fonts/MetalMania-Regular.ttf`, SIL OFL 1.1) at build time, so the player
//! embeds only an alpha-coverage bitmap: no font file and no font rasterizer at runtime
//! (README "Startup screen"). ab_glyph is a build-dependency only.
//!
//! Outputs in `OUT_DIR`: `wordmark.alpha` (row-major 8-bit coverage, tightly packed) and
//! `wordmark.rs` (`WORDMARK_SIZE`), both included by `src/splash.rs`.

use std::{env, fs, path::PathBuf};

use ab_glyph::{Font, FontRef, PxScale, ScaleFont, point};

const FONT: &str = "../../resources/fonts/MetalMania-Regular.ttf";
const TEXT: &str = "Roves";
/// Font size in physical pixels (ascent + descent of the em box scale).
const PX: f32 = 112.0;

fn main() {
    println!("cargo::rerun-if-changed={FONT}");
    println!("cargo::rerun-if-changed=build.rs");
    let bytes = fs::read(FONT).unwrap_or_else(|e| {
        panic!("{FONT}: {e} (resources/fonts must be checked out, also in sparse checkouts)")
    });
    let font = FontRef::try_from_slice(&bytes).expect("MetalMania-Regular.ttf: invalid font");
    let scale = PxScale::from(PX);
    let scaled = font.as_scaled(scale);

    let mut caret = 0.0f32;
    let mut previous = None;
    let mut outlined = Vec::new();
    for c in TEXT.chars() {
        let id = scaled.glyph_id(c);
        assert!(id.0 != 0, "MetalMania-Regular.ttf has no glyph for {c:?}");
        if let Some(previous) = previous {
            caret += scaled.kern(previous, id);
        }
        let glyph = id.with_scale_and_position(scale, point(caret, scaled.ascent()));
        caret += scaled.h_advance(id);
        previous = Some(id);
        if let Some(glyph) = font.outline_glyph(glyph) {
            outlined.push(glyph);
        }
    }
    assert!(!outlined.is_empty(), "wordmark has no outline");

    // Tight pixel bounds of the whole word.
    let (mut min_x, mut min_y, mut max_x, mut max_y) = (i32::MAX, i32::MAX, i32::MIN, i32::MIN);
    for glyph in &outlined {
        let b = glyph.px_bounds();
        min_x = min_x.min(b.min.x.floor() as i32);
        min_y = min_y.min(b.min.y.floor() as i32);
        max_x = max_x.max(b.max.x.ceil() as i32);
        max_y = max_y.max(b.max.y.ceil() as i32);
    }
    let (width, height) = ((max_x - min_x) as u32, (max_y - min_y) as u32);
    let mut alpha = vec![0f32; (width * height) as usize];
    for glyph in &outlined {
        let b = glyph.px_bounds();
        let (ox, oy) = (b.min.x as i32 - min_x, b.min.y as i32 - min_y);
        glyph.draw(|x, y, coverage| {
            let (px, py) = (ox + x as i32, oy + y as i32);
            if px < 0 || py < 0 || px >= width as i32 || py >= height as i32 {
                return;
            }
            let texel = &mut alpha[(py as u32 * width + px as u32) as usize];
            // Overlapping glyph edges combine like two independent coverages.
            *texel = 1.0 - (1.0 - *texel) * (1.0 - coverage.clamp(0.0, 1.0));
        });
    }
    let alpha: Vec<u8> = alpha.iter().map(|a| (a * 255.0).round() as u8).collect();
    assert!(alpha.contains(&255), "wordmark has no fully covered pixel");

    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    fs::write(out.join("wordmark.alpha"), &alpha).expect("write wordmark.alpha");
    fs::write(
        out.join("wordmark.rs"),
        format!(
            "/// Wordmark bitmap size in physical pixels (MetalMania {PX} px, generated by build.rs).\n\
             pub(crate) const WORDMARK_SIZE: (u32, u32) = ({width}, {height});\n"
        ),
    )
    .expect("write wordmark.rs");
}
